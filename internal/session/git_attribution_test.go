// The default patterns must catch the trailers/footers real tools emit and
// leave human content alone. Compiled with Go's regexp here (RE2 accepts the
// same ERE subset grep -E uses for these patterns), matched per line like the
// hook's `grep -Ev -f` does.
func TestDefaultAttributionPatterns(t *testing.T) {
	res := make([]*regexp.Regexp, 0, len(DefaultAttributionPatterns))
	for _, p := range DefaultAttributionPatterns {
		re, err := regexp.Compile(p)
		if err != nil {
			t.Fatalf("default pattern %q does not compile: %v", p, err)
		}
		res = append(res, re)
	}
	matchAny := func(line string) bool {
		for _, re := range res {
			if re.MatchString(line) {
				return true
			}
		}
		return false
	}

	stripped := []string{
		"Co-Authored-By: Claude <noreply@anthropic.com>",
		"Co-authored-by: Claude Opus <noreply@anthropic.com>",
		"Co-Authored-By: github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>",
		"Co-authored-by: aider (gpt-4o) <noreply@aider.chat>",
		"Co-Authored-By: Codex <codex@openai.com>",
		"Co-Authored-By: Cursor Agent <cursoragent@cursor.com>",
		"🤖 Generated with [Claude Code](https://claude.com/claude-code)",
		"Generated with Claude Code",
		"Generated by Copilot",
		"  Co-Authored-By: Claude <noreply@anthropic.com>",
		"Assisted-by: Gemini",
	}
	for _, line := range stripped {
		if !matchAny(line) {
			t.Errorf("default patterns should strip %q", line)
		}
	}

	kept := []string{
		"Co-Authored-By: Jane Doe <jane@corp.example>",
		"fix: handle generated files in the linter",
		"The report was generated with pandoc.", // mid-line, not a footer
		"Reviewed-by: Maciej Mensfeld <maciej@mensfeld.pl>",
		"",
	}
	for _, line := range kept {
		if matchAny(line) {
			t.Errorf("default patterns must NOT strip %q", line)
		}
	}
}

