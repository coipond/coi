// The composed managed-settings policy must include exactly the enabled parts.
func TestRenderClaudeManagedSettings(t *testing.T) {
	cases := []struct {
		suppress, strip               bool
		wantAuto, wantCoAuthor, empty bool
	}{
		{true, true, true, true, false},
		{true, false, true, false, false},
		{false, true, false, true, false},
		{false, false, false, false, true},
	}
	for _, c := range cases {
		got := renderClaudeManagedSettings(c.suppress, c.strip)
		if c.empty {
			if got != "" {
				t.Errorf("suppress=%v strip=%v: want empty, got %q", c.suppress, c.strip, got)
			}
			continue
		}
		if strings.Contains(got, "disableAutoMode") != c.wantAuto {
			t.Errorf("suppress=%v strip=%v: disableAutoMode presence wrong: %q", c.suppress, c.strip, got)
		}
		if strings.Contains(got, `"includeCoAuthoredBy": false`) != c.wantCoAuthor {
			t.Errorf("suppress=%v strip=%v: includeCoAuthoredBy presence wrong: %q", c.suppress, c.strip, got)
		}
	}
}
